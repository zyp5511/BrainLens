  const dictionaries = {
    en: Object.fromEntries(Object.keys(zhCN).map(key => [key, key])),
    "zh-CN": zhCN,
  };
  const storageKey = "brainlens_language";
  let language = /^zh/i.test(navigator.language) ? "zh-CN" : "en";
  try {
    const saved = localStorage.getItem(storageKey);
    if (Object.hasOwn(dictionaries, saved)) language = saved;
  } catch (_) {}

  function t(key, params = {}) {
    const current = dictionaries[language];
    const message = Object.hasOwn(current, key) ? current[key]
      : Object.hasOwn(dictionaries.en, key) ? dictionaries.en[key] : key;
    if (typeof message !== "string") return message;
    return message.replace(/\{(\w+)\}/g, (token, name) =>
      Object.hasOwn(params, name) ? String(params[name]) : token);
  }

  function applyLanguage(previous) {
    document.documentElement.lang = language;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.dataset.i18n;
      if (!previous || el.textContent === (dictionaries[previous][key] ?? key)) el.textContent = t(key);
    });
    for (const attr of ["title", "placeholder", "aria-label"]) {
      document.querySelectorAll(`[data-i18n-${attr}]`).forEach(el => {
        const key = el.getAttribute(`data-i18n-${attr}`);
        if (!previous || el.getAttribute(attr) === (dictionaries[previous][key] ?? key)) el.setAttribute(attr, t(key));
      });
    }
  }

  function setLanguage(next) {
    if (next === language || !Object.hasOwn(dictionaries, next)) return;
    const previous = language;
    language = next;
    try { localStorage.setItem(storageKey, next); } catch (_) {}
    applyLanguage(previous);
    document.dispatchEvent(new Event("brainlens-languagechange"));
  }

  const modelScores = {
    artifact: ["Artifact model", "artifact", "non-artifact", "real-HFO p {score}"],
    spike: ["Spike model", "no spike", "spike", "spike p {score}"],
    ehfo: ["eHFO model", "no eHFO", "eHFO", "eHFO p {score}"],
  };

  function modelScoreLabel(event, stage) {
    const value = event.scores?.[stage];
    if (!Number.isFinite(value)) return "";
    const [name, negative, positive, scoreKey] = modelScores[stage];
    const model = t(name);
    const probability = t(scoreKey, { score: value.toFixed(2) });
    const label = event.labels?.[stage];
    if (label !== 0 && label !== 1) return t("{model}: {probability}", { model, probability });
    return t("{model}: {result} ({probability})", { model, result: t(label ? positive : negative), probability });
  }

